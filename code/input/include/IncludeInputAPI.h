#pragma once

/// <summary>
/// 入力APIのヘッダをまとめてincludeするための集約ヘッダ。
/// DIRECTINPUT_VERSION の定義漏れによるコンパイルエラーを防ぐため、
/// 入力まわりのソースはこのヘッダ経由でincludeする
/// </summary>

// dinput.h より前に必ず定義しておく必要がある。
// 未定義のまま dinput.h をincludeすると「既定バージョンを使う」旨の警告が出るうえ、
// 参照する構造体・インターフェースのバージョンが意図せず変わってしまう。
// 0x0800 = DirectInput8（キーボード・マウスで使用しているバージョン）
#define DIRECTINPUT_VERSION 0x0800

/// ===================================================================================================
/// input API (順不同)
/// ===================================================================================================
#include <Windows.h>

// ComPtr（DirectInputのインターフェースを参照カウントで管理するために使う）
#include <wrl.h>

// キーボード・マウスは DirectInput8、ゲームパッドは XInput と、デバイスによってAPIが分かれている
#include <dinput.h>
#include <Xinput.h>
